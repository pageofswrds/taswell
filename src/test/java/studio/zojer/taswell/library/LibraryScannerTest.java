package studio.zojer.taswell.library;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import studio.zojer.taswell.track.Track;
import studio.zojer.taswell.track.TrackSource;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Exercises {@link LibraryScanner} against real fixture files under
 * {@code src/test/resources/fixtures/} (synthetic silence generated by ffmpeg, see the
 * task brief). Pure JVM — no Minecraft classes involved.
 */
class LibraryScannerTest {

    private static void copyFixture(String name, Path into) {
        String resource = "/fixtures/" + name;
        try (InputStream in = LibraryScannerTest.class.getResourceAsStream(resource)) {
            if (in == null) {
                throw new IllegalStateException("missing test fixture " + resource);
            }
            Files.copy(in, into.resolve(name));
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    @Test
    void taggedMp3YieldsTitleAndArtistFromId3(@TempDir Path dir) {
        copyFixture("one.mp3", dir);

        List<Track> tracks = LibraryScanner.scan(dir);

        assertEquals(1, tracks.size());
        Track t = tracks.get(0);
        assertEquals("Fixture One", t.title());
        assertEquals("Test Artist", t.artist());
        assertEquals(TrackSource.LOCAL, t.source());
        assertEquals("local:one.mp3", t.id());
        assertEquals(dir.resolve("one.mp3"), t.localFile());
        assertEquals(null, t.vanillaSoundEventId());
    }

    @Test
    void untaggedMp3FallsBackToFilenameStemAndEmptyArtist(@TempDir Path dir) {
        copyFixture("untagged.mp3", dir);

        List<Track> tracks = LibraryScanner.scan(dir);

        assertEquals(1, tracks.size());
        Track t = tracks.get(0);
        assertEquals("untagged", t.title());
        assertEquals("", t.artist());
        assertEquals("local:untagged.mp3", t.id());
    }

    @Test
    void wavFilesAreIncluded(@TempDir Path dir) {
        copyFixture("tiny.wav", dir);

        List<Track> tracks = LibraryScanner.scan(dir);

        assertEquals(1, tracks.size());
        assertEquals("local:tiny.wav", tracks.get(0).id());
    }

    @Test
    void corruptMp3IsIncludedWithFilenameFallback(@TempDir Path dir) {
        copyFixture("corrupt.mp3", dir);

        List<Track> tracks = LibraryScanner.scan(dir);

        assertEquals(1, tracks.size());
        Track t = tracks.get(0);
        assertEquals("corrupt", t.title());
        assertEquals("", t.artist());
        assertEquals("local:corrupt.mp3", t.id());
    }

    @Test
    void nonAudioExtensionsAreIgnored(@TempDir Path dir) throws IOException {
        copyFixture("one.mp3", dir);
        Files.writeString(dir.resolve("notes.txt"), "not audio");
        Files.writeString(dir.resolve("cover.jpg"), "not audio either");

        List<Track> tracks = LibraryScanner.scan(dir);

        assertEquals(1, tracks.size());
        assertEquals("local:one.mp3", tracks.get(0).id());
    }

    @Test
    void missingFolderYieldsEmptyListWithoutThrowing(@TempDir Path dir) {
        Path missing = dir.resolve("does-not-exist");

        List<Track> tracks = LibraryScanner.scan(missing);

        assertTrue(tracks.isEmpty());
    }

    @Test
    void subfoldersAreNotDescendedInto(@TempDir Path dir) throws IOException {
        copyFixture("one.mp3", dir);
        Path sub = dir.resolve("subdir");
        Files.createDirectory(sub);
        copyFixture("tiny.wav", sub);

        List<Track> tracks = LibraryScanner.scan(dir);

        assertEquals(1, tracks.size());
        assertEquals("local:one.mp3", tracks.get(0).id());
    }

    @Test
    void resultsAreSortedByTitle(@TempDir Path dir) throws IOException {
        // "one.mp3" tags to title "Fixture One"; add an untagged file whose filename
        // stem sorts before it alphabetically.
        copyFixture("one.mp3", dir);
        copyFixture("untagged.mp3", dir); // title falls back to "untagged"

        List<Track> tracks = LibraryScanner.scan(dir);

        assertEquals(2, tracks.size());
        assertEquals("Fixture One", tracks.get(0).title());
        assertEquals("untagged", tracks.get(1).title());
    }

    @Test
    void everyResultIsLocalSourceWithNoVanillaSoundEventId(@TempDir Path dir) {
        copyFixture("one.mp3", dir);

        Track t = LibraryScanner.scan(dir).get(0);

        assertEquals(TrackSource.LOCAL, t.source());
        assertEquals(Optional.empty(), Optional.ofNullable(t.vanillaSoundEventId()));
    }
}
